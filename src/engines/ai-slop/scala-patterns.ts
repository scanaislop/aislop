import fs from "node:fs";
import path from "node:path";
import { relativePosix } from "../../utils/paths.js";
import { getSourceFiles, isAutoGenerated } from "../../utils/source-files.js";
import { maskStringsAndComments } from "../../utils/source-masker.js";
import type { Diagnostic, EngineContext } from "../types.js";
import { isNonProductionPath } from "./non-production-paths.js";
import { isDiscardedScalaCatch, type ScalaCatchBlock, scalaCatchBlocks } from "./scala-catches.js";

const SCALA_EXTENSIONS = new Set([".scala", ".sc"]);
const SCALA_TEST_PATH_RE = /(?:^|\/)src\/test\/|(?:Spec|Suite|Test|IT)\.(?:scala|sc)$/;
const MAIN_RE = /\bdef\s+main\s*\(|@main\b|\bextends\s+(?:App|IOApp)\b/;
const PRINT_CALL_RE =
	/\bprintln\s*\(|\bConsole\s*\.\s*(?:println|print|printf)\s*\(|\bSystem\s*\.\s*(?:out|err)\s*\.\s*(?:println|print|printf|format)\s*\(/;
const IMPORT_RE = /^\s*import\s+(.+?)\s*$/;
const BROAD_CATCH_TYPES = new Set(["Throwable", "Exception"]);

const finding = (
	filePath: string,
	line: number,
	rule: string,
	message: string,
	help: string,
): Diagnostic => ({
	filePath,
	engine: "ai-slop",
	rule,
	severity: "warning",
	message,
	help,
	line,
	column: 1,
	category: "AI Slop",
	fixable: false,
});

const lineAt = (content: string, index: number): number =>
	content.slice(0, index).split("\n").length;

// Scala imports can supply implicits without a textual reference. Only Java
// imports can be checked for unused names without Scala compiler information.
const importNames = (statement: string): string[] => {
	if (!/^(?:java|javax|jakarta)\./.test(statement) || /\bgiven\b/.test(statement)) return [];
	const selector = /\.\{([^}]*)\}\s*$/.exec(statement);
	const entries = selector ? selector[1].split(",") : [statement];
	return entries.flatMap((rawEntry) => {
		const entry = rawEntry.trim();
		const renamed = /(?:=>|\bas\b)\s*([A-Za-z_$][\w$]*)\s*$/.exec(entry);
		const name = renamed?.[1] ?? entry.split(".").pop() ?? "";
		return name !== "_" && /^[A-Za-z_$][\w$]*$/.test(name) ? [name] : [];
	});
};

const isScaladocReference = (rawBody: string, name: string): boolean =>
	rawBody.includes(`[[${name}`) || rawBody.includes(`[[${name}]`) || rawBody.includes(`[[${name}|`);

const detectImports = (raw: string, masked: string, relPath: string): Diagnostic[] => {
	const diagnostics: Diagnostic[] = [];
	const rawLines = raw.split("\n");
	const maskedLines = masked.split("\n");
	const seen = new Map<string, number>();
	const importLines = new Set<number>();
	const imports: Array<{ line: number; name: string; full: string }> = [];
	for (let i = 0; i < maskedLines.length; i++) {
		const match = IMPORT_RE.exec(maskedLines[i]);
		if (!match) {
			if (maskedLines[i].trim()) seen.clear();
			continue;
		}
		importLines.add(i);
		const full = match[1];
		if (seen.has(full)) {
			diagnostics.push(
				finding(
					relPath,
					i + 1,
					"ai-slop/duplicate-import",
					`Duplicate import of ${full}`,
					"Remove the repeated import line",
				),
			);
			continue;
		}
		seen.set(full, i);
		for (const name of importNames(full)) {
			imports.push({ line: i, name, full });
		}
	}
	const body = maskedLines.filter((_, idx) => !importLines.has(idx)).join("\n");
	const rawBody = rawLines.filter((_, idx) => !importLines.has(idx)).join("\n");
	for (const { line, name, full } of imports) {
		if (
			!name ||
			new RegExp(`(?<![\\w$])${name.replaceAll("$", "\\$")}(?![\\w$])`).test(body) ||
			isScaladocReference(rawBody, name)
		)
			continue;
		diagnostics.push(
			finding(
				relPath,
				line + 1,
				"ai-slop/unused-import",
				`Unused import ${full}`,
				"Remove the import; nothing in this file references it",
			),
		);
	}
	return diagnostics;
};

const detectPrintLeftovers = (masked: string, relPath: string): Diagnostic[] => {
	if (MAIN_RE.test(masked)) return [];
	return masked
		.split("\n")
		.flatMap((line, i) =>
			PRINT_CALL_RE.test(line)
				? [
						finding(
							relPath,
							i + 1,
							"ai-slop/console-leftover",
							"println left in production code",
							"Remove the debugging output or use the project's logger",
						),
					]
				: [],
		);
};

const detectSwallowedCatches = (
	masked: string,
	relPath: string,
	blocks: ScalaCatchBlock[],
): Diagnostic[] => {
	const diagnostics: Diagnostic[] = [];
	for (const { index, clauses } of blocks) {
		if (clauses.length === 0) continue;
		if (!clauses.some((clause) => isDiscardedScalaCatch(clause.body))) continue;
		diagnostics.push(
			finding(
				relPath,
				lineAt(masked, index),
				"ai-slop/swallowed-exception",
				"Catch clause discards an exception and carries on",
				"Handle the error, rethrow it (wrapped if needed), or log it through the project's logger with context",
			),
		);
	}
	return diagnostics;
};

const detectBroadCatches = (
	masked: string,
	relPath: string,
	blocks: ScalaCatchBlock[],
): Diagnostic[] => {
	const diagnostics: Diagnostic[] = [];
	for (const { clauses } of blocks) {
		for (const clause of clauses) {
			const typeMatch = /:\s*([\w.]+)\s*$/.exec(clause.pattern.trim());
			const typeName = typeMatch?.[1].split(".").pop() ?? "";
			if (!BROAD_CATCH_TYPES.has(typeName)) continue;
			if (/\bthrow\b/.test(clause.body)) continue;
			diagnostics.push(
				finding(
					relPath,
					lineAt(masked, clause.index),
					"ai-slop/scala-broad-catch",
					`Catch clause handles ${typeName}, which buries specific failures`,
					"Match the specific exception types this code can recover from, or rethrow the rest",
				),
			);
		}
	}
	return diagnostics;
};

export const detectScalaPatterns = async (context: EngineContext): Promise<Diagnostic[]> => {
	const diagnostics: Diagnostic[] = [];
	for (const filePath of getSourceFiles(context)) {
		if (!SCALA_EXTENSIONS.has(path.extname(filePath))) continue;
		if (isAutoGenerated(filePath)) continue;
		let raw: string;
		try {
			raw = fs.readFileSync(filePath, "utf-8");
		} catch {
			continue;
		}
		const relPath = relativePosix(context.rootDirectory, filePath);
		const masked = maskStringsAndComments(raw, path.extname(filePath));
		diagnostics.push(...detectImports(raw, masked, relPath));
		if (isNonProductionPath(relPath) || SCALA_TEST_PATH_RE.test(relPath)) continue;
		diagnostics.push(...detectPrintLeftovers(masked, relPath));
		const catches = scalaCatchBlocks(masked);
		diagnostics.push(...detectSwallowedCatches(masked, relPath, catches));
		diagnostics.push(...detectBroadCatches(masked, relPath, catches));
	}
	return diagnostics;
};
