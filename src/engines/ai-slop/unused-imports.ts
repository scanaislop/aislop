import fs from "node:fs";
import path from "node:path";
import { relativePosix } from "../../utils/paths.js";
import { getSourceFiles, isAutoGenerated } from "../../utils/source-files.js";
import { filterConsumedFacadeImports } from "../python-facade.js";
import type { Diagnostic, EngineContext } from "../types.js";

export const JS_EXTENSIONS = new Set([".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs"]);
export const PY_EXTENSIONS = new Set([".py"]);
export const REMOVE_MARKER = "\0__AISLOP_REMOVE__";

export interface ImportedSymbol {
	name: string;
	line: number;
	isDefault: boolean;
	isNamespace: boolean;
}

const extractJsImportedSymbols = (
	lines: string[],
): { symbols: ImportedSymbol[]; importLines: Set<number> } => {
	const symbols: ImportedSymbol[] = [];
	const importLines = new Set<number>();

	for (let i = 0; i < lines.length; i++) {
		const line = lines[i];
		const trimmed = line.trim();

		if (!trimmed.startsWith("import ")) continue;

		importLines.add(i);

		if (/^import\s+["']/.test(trimmed)) continue;
		if (/^import\s+type\s/.test(trimmed)) continue;

		let fullImport = trimmed;
		let endLine = i;
		while (!fullImport.includes("from") && endLine < lines.length - 1) {
			endLine++;
			fullImport += ` ${lines[endLine].trim()}`;
			importLines.add(endLine);
		}

		const namespaceMatch = fullImport.match(/import\s+\*\s+as\s+(\w+)\s+from/);
		if (namespaceMatch) {
			symbols.push({
				name: namespaceMatch[1],
				line: i + 1,
				isDefault: false,
				isNamespace: true,
			});
			continue;
		}

		const defaultMatch = fullImport.match(/import\s+(\w+)\s*(?:,\s*\{[^}]*\})?\s+from/);
		if (defaultMatch && defaultMatch[1] !== "type") {
			symbols.push({
				name: defaultMatch[1],
				line: i + 1,
				isDefault: true,
				isNamespace: false,
			});
		}

		const namedMatch = fullImport.match(/\{([^}]+)\}/);
		if (namedMatch) {
			const namedImports = namedMatch[1].split(",");
			for (const ni of namedImports) {
				const parts = ni.trim().split(/\s+as\s+/);
				if (parts.length === 0 || !parts[0]) continue;
				const cleanParts = parts.map((p) => p.trim().replace(/^type\s+/, ""));
				const localName = cleanParts.length > 1 ? cleanParts[1] : cleanParts[0];
				if (localName && /^\w+$/.test(localName)) {
					symbols.push({
						name: localName,
						line: i + 1,
						isDefault: false,
						isNamespace: false,
					});
				}
			}
		}
	}

	return { symbols, importLines };
};

const extractPyImportedSymbols = (
	lines: string[],
): { symbols: ImportedSymbol[]; importLines: Set<number> } => {
	const symbols: ImportedSymbol[] = [];
	const importLines = new Set<number>();

	for (let i = 0; i < lines.length; i++) {
		const trimmed = lines[i].trim();

		const fromMatch = trimmed.match(/^from\s+([\w.]+)\s+import\s+(.+)/);
		if (fromMatch) {
			importLines.add(i);
			// `from __future__ import ...` is a parser directive, not a name that gets used.
			if (fromMatch[1] === "__future__") continue;
			const importPart = fromMatch[2].replace(/#.*$/, "").trim();
			if (importPart === "*") continue;
			const cleaned = importPart.replace(/[()]/g, "");
			for (const item of cleaned.split(",")) {
				const parts = item.trim().split(/\s+as\s+/);
				const original = parts[0].trim();
				const localName = parts.length > 1 ? parts[1].trim() : original;
				// PEP 484 re-export convention: `from X import Y as Y` explicitly publishes Y.
				if (parts.length > 1 && original === localName) continue;
				if (localName && /^\w+$/.test(localName)) {
					symbols.push({
						name: localName,
						line: i + 1,
						isDefault: false,
						isNamespace: false,
					});
				}
			}
			continue;
		}

		const importMatch = trimmed.match(/^import\s+(.+)/);
		if (importMatch) {
			importLines.add(i);
			// `import a, b.c as d` binds each comma-separated clause independently;
			// capturing only the first would delete the whole line for one unused name.
			for (const clause of importMatch[1].replace(/#.*$/, "").split(",")) {
				const clauseMatch = clause.trim().match(/^([\w.]+)(?:\s+as\s+(\w+))?/);
				if (!clauseMatch) continue;
				const alias = clauseMatch[2];
				// `import X as X` is a re-export marker.
				if (alias && alias === clauseMatch[1]) continue;
				const localName = alias ?? clauseMatch[1];
				const simpleName = localName.split(".")[0];
				if (simpleName && /^\w+$/.test(simpleName)) {
					symbols.push({
						name: simpleName,
						line: i + 1,
						isDefault: false,
						isNamespace: true,
					});
				}
			}
		}
	}

	return { symbols, importLines };
};

export const analyzeFile = (
	filePath: string,
): {
	lines: string[];
	symbols: ImportedSymbol[];
	importLines: Set<number>;
	ext: string;
} | null => {
	const ext = path.extname(filePath);
	if ((!JS_EXTENSIONS.has(ext) && !PY_EXTENSIONS.has(ext)) || isAutoGenerated(filePath))
		return null;
	let content: string;
	try {
		content = fs.readFileSync(filePath, "utf-8");
	} catch {
		return null;
	}

	const lines = content.split("\n");
	const { symbols, importLines } = PY_EXTENSIONS.has(ext)
		? extractPyImportedSymbols(lines)
		: extractJsImportedSymbols(lines);

	return { lines, symbols, importLines, ext };
};

export const getUnusedSymbols = (
	lines: string[],
	symbols: ImportedSymbol[],
	importLines: Set<number>,
): ImportedSymbol[] => {
	if (symbols.length === 0) return [];
	const body = lines.filter((_, index) => !importLines.has(index)).join("\n");
	return symbols.filter((symbol) => !body.includes(symbol.name));
};

export const detectUnusedImports = async (context: EngineContext): Promise<Diagnostic[]> => {
	const files = getSourceFiles(context);
	const diagnostics: Diagnostic[] = [];

	for (const filePath of files) {
		const analysis = analyzeFile(filePath);
		if (!analysis) continue;

		const relativePath = relativePosix(context.rootDirectory, filePath);
		const unused = getUnusedSymbols(analysis.lines, analysis.symbols, analysis.importLines);

		for (const symbol of unused) {
			diagnostics.push({
				filePath: relativePath,
				engine: "ai-slop",
				rule: "ai-slop/unused-import",
				severity: "warning",
				message: `Imported symbol '${symbol.name}' is never used`,
				help:
					path.basename(filePath) === "__init__.py"
						? "Check whether this name is part of the public package API before removing it."
						: "Remove unused imports to keep the code clean",
				line: symbol.line,
				column: 0,
				category: "AI Slop",
				fixable: path.basename(filePath) !== "__init__.py",
			});
		}
	}

	return filterConsumedFacadeImports(diagnostics, context);
};
